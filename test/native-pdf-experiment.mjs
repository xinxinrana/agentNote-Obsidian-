import assert from 'node:assert/strict';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import { JSDOM } from 'jsdom';
const require = createRequire(import.meta.url);
const dom = new JSDOM('<!doctype html><html><head><style>.native-layout{display:grid;grid-template-columns:1fr 1fr}.native-layout svg{color:purple}@font-face{font-family:Math;src:url(public/math.woff)}</style></head><body></body></html>', { url: 'app://obsidian.md/index.html' });
const { document } = dom.window;
dom.window.HTMLElement.prototype.createDiv = function(options = {}) { const el = document.createElement('div'); el.className = options.cls || ''; this.append(el); return el; };
const bundle = await build({ entryPoints: ['src/nativePdfExperiment.ts'], bundle: true, platform: 'node', format: 'cjs', external: ['obsidian'], loader: { '.svg': 'dataurl', '.png': 'dataurl' }, write: false, logLevel: 'silent' });
const exported = { exports: {} };
vm.runInNewContext(bundle.outputFiles[0].text, { module: exported, exports: exported.exports, document, URL, Buffer, process, AbortSignal, window: { fetch: async url => ({ ok: true, headers: { get: () => url.endsWith('.woff') ? 'font/woff' : 'image/png' }, arrayBuffer: async () => new Uint8Array([1, 2, 3]).buffer }) }, require: name => name === 'obsidian' ? { Component: class {} } : require(name) });
let children = 0, detached = 0, calls = 0;
const parent = { addChild(component) { children++; return component; }, removeChild() { children--; } };
const file = { path: 'note.md', basename: 'Native <note>', extension: 'md' };
const leaf = { view: { file, async print(host, component, title) {
  calls++; assert.equal(title, false); assert.ok(host.classList.contains('print'));
  const el = host.createDiv({ cls: 'markdown-preview-view markdown-rendered' });
  el.innerHTML = '<div class="native-layout" style="gap:12px"><p>Native body</p><svg viewBox="0 0 20 20"><path d="M0 0L20 20"/></svg></div><img src="app://local/image.png" onload="alert(1)"><script>bad()</script>';
  return el;
} }, async openFile(target) { assert.equal(target, file); }, detach() { detached++; } };
const app = { vault: { getFileByPath(path) { return path === file.path ? file : null; } }, workspace: { getLeavesOfType() { return [leaf]; }, getLeaf() { return leaf; } } };
try {
  const html = await exported.exports.renderNativePdfDocument(app, parent, file.path);
  const result = new JSDOM(html).window.document;
  assert.equal(calls, 1);
  assert.equal(result.querySelector('article .native-layout').getAttribute('style'), 'gap:12px');
  assert.ok(result.querySelector('article svg path'));
  assert.match(result.querySelector('style').textContent, /grid-template-columns: 1fr 1fr/);
  assert.match(result.querySelector('style').textContent, /data:font\/woff;base64,/);
  assert.ok(result.querySelector('main.print.agentnote-export-document'));
  assert.equal(result.querySelector('header h1').textContent, file.basename);
  assert.ok(result.querySelector('header img').src.startsWith('data:'));
  assert.match(result.querySelector('article img').src, /^data:image\/png;base64,/);
  assert.doesNotMatch(html, /app:\/\//);
  assert.equal(result.querySelector('script,[onload]'), null);
  assert.equal(children, 0); assert.equal(detached, 0); assert.equal(document.querySelector('.agentnote-native-render-host'), null);
  const print = leaf.view.print;
  leaf.view.print = undefined;
  await assert.rejects(exported.exports.renderNativePdfDocument(app, parent, file.path), /不支持融合导出/);
  assert.equal(children, 0);
  leaf.view.print = async () => { throw new Error('render failed'); };
  app.workspace.getLeavesOfType = () => [];
  await assert.rejects(exported.exports.renderNativePdfDocument(app, parent, file.path), /render failed/);
  assert.equal(detached, 1); assert.equal(children, 0);
  leaf.view.print = async (...args) => { const el = await print(...args); el.createDiv().innerHTML = '<iframe src="app://embed"></iframe>'; return el; };
  await assert.rejects(exported.exports.renderNativePdfDocument(app, parent, file.path), /交互嵌入/);
  assert.equal(detached, 2); assert.equal(children, 0);
  leaf.view.print = async (...args) => { const el = await print(...args); el.querySelector('img').src = 'https://example.com/remote.png'; return el; };
  await assert.rejects(exported.exports.renderNativePdfDocument(app, parent, file.path), /离线加载/);
  assert.equal(detached, 3); assert.equal(children, 0);
  console.log('PASS hybrid native renderer: host print invocation, SVG/layout preservation, host styles/font URLs, branding, no scripts, resource failures and cleanup');
} finally { dom.window.close(); }
