import assert from 'node:assert/strict';
import vm from 'node:vm';
import { build } from 'esbuild';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('<!doctype html><body><div id="card"></div></body>', { pretendToBeVisual: true });
const { window } = dom;
const proto = window.HTMLElement.prototype;
proto.createEl = function(tag, options = {}) {
  const child = window.document.createElement(tag);
  child.className = options.cls || '';
  child.textContent = options.text || '';
  for (const [name, value] of Object.entries(options.attr || {})) child.setAttribute(name, value);
  this.append(child);
  return child;
};
proto.createDiv = function(options) { return this.createEl('div', options); };
proto.createSpan = function(options) { return this.createEl('span', options); };
proto.setText = function(text) { this.textContent = text; };
proto.addClass = function(name) { this.classList.add(name); };
proto.removeClass = function(name) { this.classList.remove(name); };
const matches = proto.matches;
proto.matches = function(selector) { return selector === ':popover-open' ? this.dataset.open === 'true' : matches.call(this, selector); };
proto.showPopover = function() { this.removeAttribute('popover'); this.dataset.open = 'true'; this.dispatchEvent(new window.Event('toggle')); };
proto.hidePopover = function() { this.setAttribute('popover', 'auto'); this.dataset.open = 'false'; this.dispatchEvent(new window.Event('toggle')); };
proto.getBoundingClientRect = function() { return { left: 50, right: 350, top: 200, bottom: 242, width: 300, height: this.hasAttribute('popover') ? 225 : 42 }; };
const bundle = await build({ entryPoints: ['src/ui/shareButton.ts'], bundle: true, platform: 'node', format: 'cjs', external: ['obsidian'], write: false, logLevel: 'silent' });
const exported = { exports: {} };
vm.runInNewContext(bundle.outputFiles[0].text, { module: exported, exports: exported.exports, window, crypto: globalThis.crypto, require: () => ({ setIcon(element, name) { element.dataset.icon = name; } }) });
const calls = [];
let finish;
const control = exported.exports.renderShareButton(window.document.getElementById('card'), { share: format => { calls.push(format); return new Promise(resolve => { finish = resolve; }); } });
const primary = control.querySelector('.agentnote-share-primary');
const toggle = control.querySelector('.agentnote-share-toggle');
const menu = control.querySelector('[popover]');
const items = [...menu.querySelectorAll('[role="menuitem"]')];
const key = (target, value) => target.dispatchEvent(new window.KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true }));
try {
  assert.equal(control.querySelector('select'), null);
  assert.equal(primary.textContent, '分享当前笔记');
  assert.equal(menu.querySelector('[aria-checked]'), null);
  assert.equal(toggle.getAttribute('aria-controls'), menu.id);
  toggle.click();
  assert.equal(toggle.getAttribute('aria-expanded'), 'true');
  assert.equal(window.document.activeElement, items[0]);
  key(menu, 'ArrowDown');
  assert.equal(window.document.activeElement, items[1]);
  key(menu, 'End');
  assert.equal(window.document.activeElement, items[2]);
  key(menu, 'Home');
  assert.equal(window.document.activeElement, items[0]);
  key(menu, 'Escape');
  assert.equal(toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(window.document.activeElement, toggle);
  key(toggle, 'ArrowUp');
  assert.equal(window.document.activeElement, items[2]);
  const pending = items[1].onclick();
  assert.equal(toggle.getAttribute('aria-expanded'), 'false');
  assert.deepEqual(calls, ['pdf']);
  assert.equal(primary.disabled, true);
  assert.equal(toggle.disabled, true);
  assert.equal(primary.getAttribute('aria-busy'), 'true');
  await primary.onclick();
  assert.equal(calls.length, 1);
  finish(true);
  await pending;
  assert.equal(primary.textContent, '文件已复制');
  assert.equal(primary.disabled, false);
  assert.ok(control.classList.contains('is-complete'));
  const failed = items[2].onclick();
  assert.deepEqual(calls, ['pdf', 'html']);
  finish(false);
  await failed;
  assert.equal(primary.textContent, '分享当前笔记');
  const defaultAction = primary.onclick();
  assert.deepEqual(calls, ['pdf', 'html', 'link']);
  finish(false);
  await defaultAction;
  assert.equal(primary.textContent, '分享当前笔记');
  assert.equal(primary.disabled, false);
  assert.equal(primary.getAttribute('aria-busy'), 'false');
  console.log('PASS custom split button: direct menu actions, keyboard navigation, focus return, duplicate prevention, success and failure states');
} finally { dom.window.close(); }
