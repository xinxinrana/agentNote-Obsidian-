import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createRequire } from 'node:module';
const { inspectData, repairData, mergeDocumentConflicts, VaultStore } = createRequire(import.meta.url)('./core-bundle.cjs');
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'agentnote-repair-'));
const data = path.join(root, 'agentNote/data');
const doc = { id: 'd-one', path: 'note.md', title: 'Note', created: '2026-10-01T00:00:00Z', updated: '2026-10-02T00:00:00Z' };
const conflict = (a, b, base) => ['<<<<<<< HEAD', JSON.stringify(a), ...(base ? ['||||||| base', JSON.stringify(base)] : []), '=======', JSON.stringify(b), '>>>>>>> origin/main'].join('\n');
try {
  assert.equal((await inspectData(data)).length, 0);
  let result = await repairData(data);
  assert.equal(result.repaired.length, 0);
  assert.equal(result.backups.length, 0);
  assert.deepEqual(result.remaining, []);
  console.log('PASS optional legacy indexes are not created when absent');
  const later = { ...doc, updated: '2026-10-03T00:00:00Z' };
  const extra = { ...doc, id: 'd-two', path: 'other.md' };
  const raw = conflict([doc], [later, extra], [doc]);
  await fs.writeFile(path.join(data, 'documents.json'), raw);
  assert.equal((await inspectData(data))[0].canRepair, true);
  const store = new VaultStore(root, '.obsidian', { deviceIdFile: path.join(root, 'device-id') });
  const results = await Promise.all([store.repairData(), store.repairData()]);
  assert.equal(results.flatMap(r => r.repaired).length, 1);
  result = results.find(r => r.backups.length);
  assert.equal(await fs.readFile(path.join(root, result.backups[0]), 'utf8'), raw);
  const merged = JSON.parse(await fs.readFile(path.join(data, 'documents.json'), 'utf8'));
  assert.equal(merged.length, 2); assert.equal(merged[0].updated, later.updated);
  assert.equal((await repairData(data)).backups.length, 0);
  console.log('PASS diff3 conflict repairs preserve both branches, exact backups, and serialize repeated clicks');
  const ambiguous = conflict([doc], [{ ...doc, path: 'moved.md' }]);
  await fs.writeFile(path.join(data, 'documents.json'), ambiguous);
  result = await repairData(data);
  assert.equal(result.repaired.length, 0); assert.equal(result.remaining[0].canRepair, false);
  assert.equal(await fs.readFile(path.join(data, 'documents.json'), 'utf8'), ambiguous);
  assert.equal(mergeDocumentConflicts(conflict([doc], [{ ...doc, protected: true }])), null);
  assert.equal(mergeDocumentConflicts(conflict([doc], [{ ...doc, deletedAt: '2026-10-04T00:00:00Z' }])), null);
  assert.equal(mergeDocumentConflicts('<<<<<<< HEAD\n[]'), null);
  console.log('PASS ambiguous paths/protection/deletion and incomplete conflicts are never guessed');
  await fs.writeFile(path.join(data, 'documents.json'), '{ broken');
  await fs.writeFile(path.join(data, 'events.test-device.json'), '{ broken');
  result = await repairData(data);
  assert.equal(result.repaired.length, 0); assert.equal(result.remaining.length, 2);
  assert.equal(await fs.readFile(path.join(data, 'events.test-device.json'), 'utf8'), '{ broken');
  assert.equal(await fs.readFile(path.join(data, 'documents.json'), 'utf8'), '{ broken');
  console.log('PASS malformed JSON and logs remain untouched and visible as manual issues');
  const independent = path.join(data, 'events', '2026-10', '11111111-1111-4111-8111-111111111111.json');
  await fs.mkdir(path.dirname(independent), { recursive: true });
  await fs.writeFile(independent, '<<<<<<< HEAD');
  assert.equal((await inspectData(data)).some(issue => issue.file.endsWith('11111111-1111-4111-8111-111111111111.json')), true);
  assert.equal((await repairData(data)).repaired.length, 0);
  assert.equal(await fs.readFile(independent, 'utf8'), '<<<<<<< HEAD');
  await fs.rm(independent);
  await fs.rm(path.join(data, 'events'), { recursive: true });
  await fs.writeFile(path.join(data, 'events'), 'not a directory');
  assert.equal((await inspectData(data)).some(issue => issue.file === 'agentNote/data/events'), true);
  assert.equal((await repairData(data)).repaired.length, 0);
  assert.equal(await fs.readFile(path.join(data, 'events'), 'utf8'), 'not a directory');
  await fs.rm(path.join(data, 'events'));
  if (process.env.AGENTNOTE_DAMAGED_DOCUMENTS) {
    const actual = await fs.readFile(process.env.AGENTNOTE_DAMAGED_DOCUMENTS, 'utf8');
    const expected = mergeDocumentConflicts(actual);
    assert.ok(expected); await fs.writeFile(path.join(data, 'documents.json'), actual);
    await fs.rm(path.join(data, 'events.test-device.json'));
    result = await repairData(data);
    assert.equal(result.repaired.length, 1);
    assert.deepEqual(JSON.parse(await fs.readFile(path.join(data, 'documents.json'), 'utf8')), expected);
    assert.equal(await fs.readFile(path.join(root, result.backups[0]), 'utf8'), actual);
    assert.equal(await fs.readFile(process.env.AGENTNOTE_DAMAGED_DOCUMENTS, 'utf8'), actual);
    console.log('PASS actual vault conflict copy repaired with all document IDs preserved; real vault untouched');
  }
} finally { await fs.rm(root, { recursive: true, force: true }); }
